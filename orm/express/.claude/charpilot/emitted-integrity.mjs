#!/usr/bin/env node
/**
 * Was a generated test edited after it was generated?
 *
 * Every emitted file says `do not hand-edit` in its first line, and until now
 * nothing enforced it. That line is the whole contract: an assertion in these
 * files is trustworthy only because it was produced by RUNNING the code, so a
 * hand-typed expected value wears the same header as a recorded one and reads
 * as recorded in review. It is this pipeline's version of the committed
 * `actual.json` that qode-characterize's CI step refuses - an output nobody
 * approved, sitting in the tree looking approved.
 *
 * This is deliberately the ONLY charpilot check that reads nothing from
 * `.claude/charpilot/out/`. That directory is gitignored, so a CI runner has a
 * checkout with no baseline, no scan and no behaviour.json, and every other
 * check in gate.mjs is unrunnable there by construction. This one needs the
 * committed manifest and the committed tests, both of which CI has.
 *
 *   node .claude/charpilot/emitted-integrity.mjs [--tests test/characterization]
 *
 * Exit 0 means every emitted file is byte-for-byte what the emitter wrote.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join, relative } from "node:path";

import { CORPUS_REL, REPO_ROOT, isCorpusSpec } from "./config.mjs";

const ARGV = process.argv.slice(2);
const arg = (f) => (ARGV.includes(f) ? ARGV[ARGV.indexOf(f) + 1] : undefined);
const TESTS_DIR = arg("--tests") ?? CORPUS_REL;

/** Kept identical to record.mjs's EMIT_HEADER - a file carrying it claims to be generated. */
const EMIT_HEADER = "GENERATED by `.claude/charpilot/record.mjs --emit-tests`";

export const sha256 = (text) => createHash("sha256").update(text).digest("hex");

/**
 * Three ways a generated file can be wrong, and all three have to be separate
 * findings: a HASH mismatch is an edit, a MISSING file is a deleted assertion,
 * and an UNMANIFESTED file carrying the header is one the emitter wrote and the
 * manifest does not account for - which is how a stale generation survives a
 * regeneration that produced fewer files.
 *
 * A manifest with no hashes at all is a FAILURE, not a pass. The same reasoning
 * as the determinism verdict living on the row: an absent field means the file
 * was never checked, and reporting that as "unedited" is the lie the field
 * exists to prevent.
 */
export function integrity(testsDir = TESTS_DIR) {
  const dir = join(REPO_ROOT, testsDir);
  const manifestPath = join(dir, "emitted.json");
  if (!existsSync(manifestPath)) {
    return { ok: false, reason: `no manifest at ${relative(REPO_ROOT, manifestPath)} - the suite cannot say what generated it`, problems: [] };
  }
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const hashes = manifest.emittedFileHashes ?? null;
  const listed = manifest.emittedFiles ?? [];
  if (!hashes || !Object.keys(hashes).length) {
    return {
      ok: false,
      reason:
        `${relative(REPO_ROOT, manifestPath)} carries no emittedFileHashes for its ${listed.length} file(s) - ` +
        `an absent hash means the file was never checked, not that it is unedited`,
      problems: [],
    };
  }

  const problems = [];
  for (const rel of listed) {
    const path = join(REPO_ROOT, rel);
    if (!existsSync(path)) {
      problems.push({ file: rel, kind: "missing", detail: "listed in the manifest, not on disk" });
      continue;
    }
    const want = hashes[rel];
    if (!want) {
      problems.push({ file: rel, kind: "unhashed", detail: "listed but carries no hash" });
      continue;
    }
    const got = sha256(readFileSync(path, "utf8"));
    if (got !== want) {
      problems.push({ file: rel, kind: "edited", detail: `sha256 ${got.slice(0, 12)}, manifest says ${want.slice(0, 12)}` });
    }
  }

  // A file wearing the header that the manifest never claimed. Left as its own
  // finding rather than folded into "edited": nothing about its CONTENT is
  // wrong, its provenance is.
  const known = new Set(listed.map((f) => f.split("/").pop()));
  const present = existsSync(dir) ? readdirSync(dir).filter(isCorpusSpec) : [];
  for (const f of present) {
    if (known.has(f)) continue;
    const head = readFileSync(join(dir, f), "utf8").slice(0, 400);
    if (head.includes(EMIT_HEADER)) {
      problems.push({ file: join(testsDir, f), kind: "unmanifested", detail: "carries the generated header, absent from the manifest" });
    }
  }

  return { ok: problems.length === 0, reason: null, problems, checked: listed.length, emittedAt: manifest.emittedAt ?? null };
}

function main() {
  const r = integrity();
  if (r.reason) {
    process.stderr.write(`! emitted-integrity: ${r.reason}\n  fix: npm run pilot:emit\n`);
    process.exit(1);
  }
  if (!r.ok) {
    process.stderr.write(
      `! emitted-integrity: ${r.problems.length} problem(s) across ${r.checked} generated file(s)\n` +
        r.problems.map((p) => `  ${p.kind.toUpperCase()}  ${p.file} - ${p.detail}\n`).join("") +
        `\n  An EDITED generated test is an expected value nobody recorded. Re-record the row and re-emit;\n` +
        `  do not edit the value until it passes. If the edit was deliberate, move that test out of\n` +
        `  ${TESTS_DIR} so it stops claiming to be generated.\n`
    );
    process.exit(1);
  }
  process.stdout.write(`· emitted-integrity: ${r.checked} generated file(s) unedited since ${r.emittedAt ?? "the last emit"}\n`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
